import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { existsSync,mkdirSync,readFileSync,writeFileSync } from 'node:fs';
import { verifiedStripeSandbox,savePrivateEnvironment } from './lib/stripe-sandbox';
import { verifyProject,connectDatabase,inspectDatabase,ReadinessError,safeFailure } from './lib/database';
import { management,deployFunction } from './lib/management';
const file='.tools/private/payment-platform.json';const slug='palmsteeze-payments';
type State={token:string;endpointID?:string;signingSecret?:string;functionCreated?:boolean};
const save=(state:State)=>{mkdirSync('.tools/private',{recursive:true});writeFileSync(file,JSON.stringify(state),{mode:0o600});};
async function main() {
  await verifyProject();const stripe=await verifiedStripeSandbox();
  const state:State=existsSync(file) ? JSON.parse(readFileSync(file,'utf8')):{token:randomBytes(32).toString('base64url')};save(state);
  const endpoint=`${process.env.NEXT_PUBLIC_SUPABASE_URL}/functions/v1/${slug}`;
  if(process.argv[2]==='prepare') {
    const functions=await(await management('functions')).json() as {slug:string}[];
    if(functions.some(f=>f.slug===slug) && !state.functionCreated) throw new ReadinessError('NOT RUN: existing payment function is not tracked as this workspace resource; refused overwrite.');
    if(!state.endpointID) {
      try {
        const webhook=await stripe.webhookEndpoints.create({url:`${endpoint}/webhook`,api_version:'2026-09-30.endive',
          enabled_events:['checkout.session.completed','checkout.session.expired','payment_intent.succeeded','refund.created','refund.updated','refund.failed','charge.refunded'],
          description:'PalmSteeze dedicated development sandbox payment receiver',metadata:{palmsteeze_environment:'development'}},
        {idempotencyKey:`palmsteeze-webhook-${process.env.SUPABASE_PROJECT_REF}`});
        assert.equal(webhook.livemode,false);assert.equal(webhook.url,`${endpoint}/webhook`);assert.ok(webhook.secret);
        state.endpointID=webhook.id;state.signingSecret=webhook.secret;save(state);
      } catch(error) {
        const e=error as {statusCode?:number};
        throw new ReadinessError(`NOT RUN: create sandbox webhook endpoint returned HTTP ${e.statusCode||'unavailable'}. Enable Webhook Endpoints Write privately; provider text/identity withheld.`);
      }
    } else {
      const webhook=await stripe.webhookEndpoints.retrieve(state.endpointID);
      assert.equal(webhook.url,`${endpoint}/webhook`);assert.equal(webhook.livemode,false);
      if(!webhook.enabled_events.includes('refund.failed')) await stripe.webhookEndpoints.update(state.endpointID,{enabled_events:['checkout.session.completed','checkout.session.expired','payment_intent.succeeded','refund.created','refund.updated','refund.failed','charge.refunded']});
    }
    const secrets=[{name:'PALMSTEEZE_STRIPE_KEY',value:process.env.STRIPE_SECRET_KEY!},
      {name:'PALMSTEEZE_STRIPE_WEBHOOK_SECRET',value:state.signingSecret!},
      {name:'PALMSTEEZE_PAYMENT_WORKER_TOKEN',value:state.token},{name:'PALMSTEEZE_APP_ORIGIN',value:'http://localhost:3000'}];
    const previous=await(await management('secrets')).json() as {name:string}[];
    if(!state.functionCreated && previous.some(s=>secrets.some(v=>v.name===s.name))) throw new ReadinessError('NOT RUN: pre-existing payment secrets refused; inspect workspace-owned state.');
    await management('secrets',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(secrets)});
    // Track before deploy: the token is generated by this workspace and names
    // have been inspected. A retry may safely finish this exact setup.
    state.functionCreated=true;save(state);
    await deployFunction(slug,readFileSync(`supabase/functions/${slug}/index.ts`,'utf8'));
    savePrivateEnvironment({PALMSTEEZE_PAYMENT_WORKER_TOKEN:state.token,STRIPE_WEBHOOK_SECRET:state.signingSecret!});
    console.log('PASSED: dedicated sandbox webhook and protected development payment Edge function configured. Credentials captured privately; no Next.js publication, paid service or schedule enabled.');return;
  }
  if(process.argv[2]!=='enable-schedule' || !state.functionCreated) throw new ReadinessError('NOT RUN: prepare payment platform before enabling its operational schedule.');
  const client=await connectDatabase();
  try {
    await inspectDatabase(client);await client.query('begin');
    for(const [name,value] of [['palmsteeze_payment_worker_url',`${endpoint}/recover`],['palmsteeze_payment_worker_token',state.token]]) {
      const existing=await client.query('select id from vault.secrets where name=$1',[name]);
      if(existing.rowCount) await client.query('select vault.update_secret($1,$2)',[existing.rows[0].id,value]);
      else await client.query('select vault.create_secret($1,$2,$3)',[value,name,'PalmSteeze development payment recovery']);
    }
    const previous=await client.query("select jobid,schedule,command from cron.job where jobname='palmsteeze-payment-recovery'");
    if(previous.rowCount) {
      assert.equal(previous.rows[0].schedule,'* * * * *');assert.equal(previous.rows[0].command,'select private.invoke_payment_recovery()');
    } else await client.query("select cron.schedule('palmsteeze-payment-recovery','* * * * *','select private.invoke_payment_recovery()')");
    await client.query('commit');console.log('PASSED: documented development operational minute schedule enabled; opaque token kept in Vault. At most two jobs per call, no paid services.');
  } catch(error) {await client.query('rollback');throw error;} finally {await client.end();}
}
main().catch(safeFailure);
